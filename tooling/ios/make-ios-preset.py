#!/usr/bin/env python3
"""Derive the engine's iOS copy of the shipped `standard` agent preset.

The web bundle ships `packages/bundle/web-app/presets/standard.patch.yml`, which
inserts a `preset-standard` row carrying the plugin list every session starts
with. That list includes `tool-bash` and `tool-pwsh`; on iOS both spawn a process
and fail per call, but a loader patch cannot reach them -- preset rows live in
their own scope, so the only way to change them is to replace the whole row.

`app/ios/Engine/ios.patch.yml` says as much in its "open item: preset rows"
section and stops there. This script closes it: it reads the shipped file and
writes `app/ios/Engine/ios-preset.patch.yml`, the same declaration without the two
process tools, converted from an `insert` row into the id-targeted override the
loader documents ("Change a shipped preset" in
`packages/preset/agent-preset/skills/dsh-doc/references/compositions.md`).

Regenerate after any change to the shipped preset:

    tooling/ios/make-ios-preset.py            # write the file
    tooling/ios/make-ios-preset.py --check    # exit 1 if it is stale

Nothing else reads the shipped file at runtime: the app ships the two YAML files
and host.mjs passes both to `--patch`, in that order.
"""

from __future__ import annotations

import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "packages/bundle/web-app/presets/standard.patch.yml"
OUTPUT = ROOT / "app/ios/Engine/ios-preset.patch.yml"

# Dropped from the catalog: no fork/exec on iOS, so every call would be a spawn
# error. `tool-fs`, `tool-fs-search` and the rest stay.
DROPPED = ("tool-bash", "tool-pwsh")

HEADER = """\
# GENERATED by tooling/ios/make-ios-preset.py from
# packages/bundle/web-app/presets/standard.patch.yml -- do not edit by hand.
#
# The `standard` preset with the two process tools removed. iOS has no fork/exec
# inside the app sandbox, so `tool-bash` and `tool-pwsh` can only ever fail; the
# rest of the plugin list is the shipped one, restated because a patch replaces a
# row's whole `config` (see "Change a shipped preset" in the dsh-doc references).
# host.mjs passes this after ios.patch.yml, and both after the bundle's own
# `presets/standard.patch.yml`.

"""


def fail(message: str) -> "None":
    print(f"make-ios-preset: {message}", file=sys.stderr)
    raise SystemExit(1)


def plugin_indent(lines: list[str]) -> int:
    """Indentation of the `- id:` entries directly under `plugins:`."""
    for number, line in enumerate(lines):
        if line.strip() == "plugins:":
            for candidate in lines[number + 1:]:
                if not candidate.strip() or candidate.lstrip().startswith("#"):
                    continue
                if not candidate.lstrip().startswith("- "):
                    fail(f"expected a plugin entry under `plugins:` at line {number + 1}, found {candidate.strip()!r}")
                return len(candidate) - len(candidate.lstrip())
    fail("no `plugins:` key in the shipped preset")
    return 0


def build(source_text: str) -> str:
    lines = source_text.splitlines()

    insert_at = next((n for n, line in enumerate(lines) if line.strip() == "- insert:"), None)
    if insert_at is None:
        fail("the shipped preset is not an `- insert:` row any more; re-read the override syntax")
    row_at = next((n for n in range(insert_at + 1, len(lines)) if lines[n].strip().startswith("- id: preset-standard")), None)
    if row_at is None:
        fail("the shipped preset no longer inserts a `preset-standard` row")

    # `- insert:` wraps the row one level deeper; an override names the row at the
    # top level, so the whole block loses those four spaces.
    body = [lines[row_at][4:]] + [line[4:] if line.startswith("    ") else line.lstrip() for line in lines[row_at + 1:]]
    # `[4:]` on the first line also drops the list dash's indentation.
    body[0] = "- " + body[0].strip()[2:] if body[0].strip().startswith("- ") else body[0]

    indent = plugin_indent(body)
    marker = " " * indent

    kept: list[str] = []
    dropped: list[str] = []
    skipping = False
    for line in body:
        if skipping:
            # A plugin entry ends at the next entry or at the end of the list.
            if line.startswith(marker + "- ") or (line.strip() and not line.startswith(" " * (indent + 1))):
                skipping = False
            else:
                continue
        if line.startswith(marker + "- id: "):
            name = line[len(marker) + len("- id: "):].strip()
            if name in DROPPED:
                dropped.append(name)
                skipping = True
                continue
        kept.append(line)

    missing = [name for name in DROPPED if name not in dropped]
    if missing:
        fail(f"the shipped preset has no {', '.join(missing)} entry any more; the generated copy is stale by design")
    for name in DROPPED:
        if any(line.strip() == f"- id: {name}" for line in kept):
            fail(f"{name} survived the rewrite")

    return HEADER + "\n".join(kept) + "\n"


def main() -> int:
    if not SOURCE.is_file():
        fail(f"{SOURCE.relative_to(ROOT)} is missing")
    generated = build(SOURCE.read_text())

    check = "--check" in sys.argv[1:]
    if check:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ""
        if current == generated:
            print(f"make-ios-preset: {OUTPUT.relative_to(ROOT)} is up to date")
            return 0
        for line in difflib.unified_diff(
            current.splitlines(), generated.splitlines(),
            fromfile=str(OUTPUT.relative_to(ROOT)), tofile="regenerated", lineterm="",
        ):
            print(line, file=sys.stderr)
        print("make-ios-preset: the shipped preset changed; run tooling/ios/make-ios-preset.py", file=sys.stderr)
        return 1

    OUTPUT.write_text(generated)
    print(f"make-ios-preset: wrote {OUTPUT.relative_to(ROOT)} ({len(generated.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
